// `npm run cap:sync`: copy the Android build into the native project with WebView settings that
// match the API it was built for.
//
// Why: Capacitor serves the app from https://localhost by default. Android's WebView refuses
// "mixed content" (MIXED_CONTENT_NEVER_ALLOW, the default for apps targeting API 21+), so an app
// on https://localhost can never reach an http:// API — not REST, not polling, not WebSockets.
// Production uses an https:// API, so it keeps the secure https://localhost origin. A build for a
// plain-HTTP API (a laptop on the local network) is served from http://localhost instead, so no
// request is mixed content; only those builds are allowed cleartext HTTP.
//
// The API URL is resolved exactly like the build (`vite build --mode android`): the VITE_API_URL
// environment variable, else .env.android(.local), else .env.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnv } from 'vite';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const apiUrl = (loadEnv('android', root, 'VITE_').VITE_API_URL || '').trim();

let protocol;
try {
  protocol = new URL(apiUrl).protocol;
} catch {
  console.error(`VITE_API_URL is "${apiUrl}". The Android app needs the server's full address, e.g.\n`
    + '  https://scores.example.com      (production)\n'
    + '  http://192.168.1.20:4000        (a laptop on the local network)\n'
    + 'Set it in apps/viewer/.env.android.');
  process.exit(1);
}
if (!['http:', 'https:'].includes(protocol)) {
  console.error(`VITE_API_URL must start with https:// or http:// (got "${apiUrl}").`);
  process.exit(1);
}
const secure = protocol === 'https:';

const sync = spawnSync('npx cap sync android', { cwd: root, stdio: 'inherit', shell: true });
if (sync.status !== 0) process.exit(sync.status ?? 1);

// The config the app reads at runtime (generated by `cap sync`, not committed).
const runtimeConfig = path.join(root, 'android/app/src/main/assets/capacitor.config.json');
const config = JSON.parse(fs.readFileSync(runtimeConfig, 'utf8'));
config.server = { ...config.server, androidScheme: secure ? 'https' : 'http' };
fs.writeFileSync(runtimeConfig, `${JSON.stringify(config, null, '\t')}\n`);

// Read by android/app/build.gradle → android:usesCleartextTraffic (not committed).
fs.writeFileSync(path.join(root, 'android/app/network.properties'),
  `# Written by scripts/cap-sync.mjs for VITE_API_URL=${apiUrl}\nusesCleartextTraffic=${!secure}\n`);

console.log(`\nAndroid: API ${apiUrl} → app served from ${secure ? 'https' : 'http'}://localhost, cleartext HTTP ${secure ? 'off' : 'on'}.`);
if (!secure) console.log('This is a local-network build. Use an https:// VITE_API_URL for the release build.');
